def replace_in_str(s):
    if not isinstance(s, str):
        return s
    for old, new in replacements:
        s = s.replace(old, new)
    return s

def replace_in_block(b):
    for field in ['text', 'question', 'answer']:
        if field in b and isinstance(b[field], str):
            b[field] = replace_in_str(b[field])
    if 'items' in b and isinstance(b['items'], list):
        b['items'] = [replace_in_str(item) for item in b['items']]
    return b

